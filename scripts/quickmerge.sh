    if ! bash scripts/quality-gates.sh --no-fix --lint $SKIP_CODEX; then
      echo "[$REPO_NAME] ❌ Lint FAILED — fix remaining issues before merging"
      exit 1
    fi

    # Phase 3: full gates minus lint (tests + typecheck + codex run exactly once)
    echo "[$REPO_NAME] Phase 3: full gates (tests + typecheck + codex, lint already verified)..."
    if ! bash scripts/quality-gates.sh --no-fix --skip-lint $SKIP_TESTS $SKIP_TYPECHECK $SKIP_CODEX; then
      echo "[$REPO_NAME] ❌ Quality gates FAILED — fix remaining issues before merging"
      exit 1
    fi
    echo "[$REPO_NAME] ✅ Quality gates PASSED"
  fi
else
  # Strict check: repos that require quality gates must have scripts/quality-gates.sh
  REPO_TYPE=""
  QG_STATUS=""
  if [ -f "${MANIFEST_PATH:-}" ]; then
    REPO_TYPE=$(jq -r '.repositories["'"$REPO_NAME"'"] | .type // empty' "$MANIFEST_PATH" 2>/dev/null)
    QG_STATUS=$(jq -r '.repositories["'"$REPO_NAME"'"] | .ci_status // empty' "$MANIFEST_PATH" 2>/dev/null)
  fi
  QG_REQUIRED_TYPES="library service api-service infrastructure devops test-harness"
  if [ -n "$REPO_TYPE" ] && [ -n "$QG_STATUS" ] && \
     echo "$QG_REQUIRED_TYPES" | grep -qw "$REPO_TYPE" && \
     [ "$QG_STATUS" != "NO_QG" ]; then
    echo "[$REPO_NAME] ❌ quality-gates.sh required: type=$REPO_TYPE, ci_status=$QG_STATUS (add scripts/quality-gates.sh or set ci_status=NO_QG in manifest)" >&2
    exit 1
  fi
  echo "[$REPO_NAME] ⚠️  No quality-gates.sh found (skipping quality gate check)"

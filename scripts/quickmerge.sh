# Auto-format with Prettier BEFORE staging (so pre-commit validation passes).
# SCOPE TO --files: a tree-wide `prettier --write "**/*"` reflows FOREIGN files (another
# slot's WIP) into working-tree residue that makes the slot perpetually dirty → the
# FF-pull cron skips it → the slot stops syncing (observed 2026-06-02: 69-file reflow
# residue). Mirrors the prettier-autostage hook's "never touch foreign-dirty files" rule.
# The on-commit prettier-autostage hook re-formats + re-stages the staged subset anyway,
# so this pre-format is only a fast-path. Only the unscoped (--files-absent) path
# formats tree-wide — there the caller owns the whole tree.
if [ -f ".pre-commit-config.yaml" ] && grep -q "mirrors-prettier\|prettier-autostage" .pre-commit-config.yaml 2>/dev/null; then
  if [ -n "$FILES_ARG" ]; then
    # M1: the sentinel was verified == HEAD ABOVE, but prettier --write here runs AFTER that
    # check, so a reformat would make the COMMITTED tree differ from the QG-certified content.
    # Detect + warn (prettier is format-only, so this is observability not a hard block; the
    # CLAUDE.md ship rule already mandates `prettier --write` BEFORE Pass-1 QG so this is a no-op
    # on the happy path). A non-empty diff here means Pass-1 ran on an unformatted tree.
    _pre_fmt_hash=""; [ "$AGENT_MODE" = true ] && _pre_fmt_hash=$(git diff -- $FILES_ARG | shasum 2>/dev/null | cut -d' ' -f1)
    # shellcheck disable=SC2086  # intentional word-split: FILES_ARG is a space-separated path list
    npx --yes prettier@3.6.2 --write --ignore-unknown $FILES_ARG >/dev/null 2>&1 || true
    if [ "$AGENT_MODE" = true ]; then
      _post_fmt_hash=$(git diff -- $FILES_ARG | shasum 2>/dev/null | cut -d' ' -f1)
      if [ -n "$_pre_fmt_hash" ] && [ "$_pre_fmt_hash" != "$_post_fmt_hash" ]; then
        echo "[$REPO_NAME] ⚠️  M1: prettier reformatted --files AFTER the Pass-1 sentinel was certified —"
        echo "    the committed tree differs from the QG-validated content (format-only, but not gate-checked)."
        echo "    Pre-format your files (prettier --write) BEFORE running Pass-1 quality-gates.sh to close this."
      fi
    fi
  else
    # Unscoped ship (caller owns the whole tree): canonical prettier@3.6.2 tree-wide.
    # (Dropped the dead `pre-commit run prettier` probe — the hook id is prettier-autostage
    # so it never matched; prek is the canonical runner now, and the on-commit hook
    # re-formats + auto-stages anyway. npx pins the canonical version on every host.)
    npx --yes prettier@3.6.2 --write "**/*.{ts,tsx,js,jsx,json,md,yaml,yml,css}" --ignore-unknown >/dev/null 2>&1 || true
    npx --yes prettier@3.6.2 --write "**/*.{ts,tsx,js,jsx,json,md,yaml,yml,css}" --ignore-unknown >/dev/null 2>&1 || true
  fi
fi

# Stage files: --files for selective add, else add all
sync 2>/dev/null || true
sleep 0.3

if [ -n "$FILES_ARG" ]; then
  ADDED_ANY=0
  for f in $FILES_ARG; do
    if [ -e "$f" ]; then
      git add "$f"
      ADDED_ANY=1
    elif git ls-files --error-unmatch -- "$f" >/dev/null 2>&1; then
      # Tracked but absent from the worktree = a DELETION — stage it. The old
      # `[ -e ]`-only guard silently dropped deleted paths from scoped commits
      # (half-shipped removals, e.g. instruments-service polygon 2026-06-10).
      git add -- "$f"
      ADDED_ANY=1
    else
      echo "[$REPO_NAME] ⚠️  Path not found (and not tracked): $f"
    fi
  done
  if [ "$ADDED_ANY" = 0 ]; then
    echo "[$REPO_NAME] ❌ No valid paths from --files. Nothing to commit."
    exit 1
  fi
  if [ -z "$(git diff --cached --name-only)" ]; then
    # No staged changes in --files paths. If the branch is already ahead of main,
    # the work was already committed (e.g. agent committed + pushed before quickmerge).
    # Fall through to the push + PR stage rather than exiting.
    AHEAD_COUNT=$(git rev-list origin/main..HEAD --count 2>/dev/null || echo "0")
    if [ "$AHEAD_COUNT" -gt 0 ]; then
      echo "[$REPO_NAME] ℹ️  No uncommitted changes in --files paths; branch is $AHEAD_COUNT commit(s) ahead of main — changes already committed. Proceeding to push + PR."
    else
      echo "[$REPO_NAME] ❌ No changes in --files paths. Nothing to commit."
      exit 1
    fi
  fi
else
  git add -A
fi

# Strict-quickmerge lineage trailer (2026-06-08): stamp every quickmerge commit so the
# strict-quickmerge guard (scripts/cicd/check_strict_quickmerge.py) can distinguish a commit
# that PASSED THROUGH quickmerge from a direct integration-branch code push that bypassed it.
# Kept out of COMMIT_MSG (the PR title) — only the git commit message carries it.
_QM_TRAILER_KIND="human"; [ "$AGENT_MODE" = true ] && _QM_TRAILER_KIND="agent"
_QM_COMMIT_MSG="$(printf '%s\n\nQuickmerge: %s' "$COMMIT_MSG" "$_QM_TRAILER_KIND")"

if [ -z "$(git diff --cached --name-only)" ] && [ -z "$(git status --porcelain)" ]; then
  # Nothing staged and working tree is clean — changes were already committed
  # in a previous quickmerge run. Skip commit and go straight to push + PR.
  echo "[$REPO_NAME] ℹ️  Working tree clean — changes already committed. Proceeding to push."
elif ! git commit -m "$_QM_COMMIT_MSG" --quiet; then
  # Pre-commit may have modified files (e.g. Prettier). Re-stage and retry once.
  # RE-ASSERT --files SCOPE: a hook that reformats files must NOT let `git add -A`
  # sweep FOREIGN modified files (another agent's WIP, an inventory regen, a concurrent
  # edit) into a scoped commit — that is the prek-auto-stage-vs-`--files` foot-gun. When
  # --files is set, re-stage ONLY those paths (the hook's edits to YOUR files re-stage;
  # foreign modified files stay out of the index). Only the unscoped path uses `git add -A`.
  if [ -n "$FILES_ARG" ]; then
    for f in $FILES_ARG; do
      # Deletion-aware re-stage (same rule as the primary loop): tracked-but-absent = deletion.
      if [ -e "$f" ] || git ls-files --error-unmatch -- "$f" >/dev/null 2>&1; then git add -- "$f"; fi
    done
  else
    git add -A
  fi
  if ! git commit -m "$_QM_COMMIT_MSG" --quiet; then
    echo "[$REPO_NAME] ❌ Commit failed (pre-commit may have failed). Run: pre-commit run --all-files; git add -A; git commit -m \"...\"" >&2
    exit 1
  fi
  if [ -n "$FILES_ARG" ]; then
    echo "[$REPO_NAME] Pre-commit modified files; re-staged (scoped to --files) and committed on retry" >&2
  else
    echo "[$REPO_NAME] Pre-commit modified files; staged and committed on retry" >&2
  fi
fi

